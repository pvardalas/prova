def fmt_date(d, style):
    if style == 0:
        return f"{d.day}/{d.month}/{d.year % 100}"
    if style == 1:
        return d.isoformat()
    if style == 2:
        return f"{MONTHS[d.month - 1]} {d.year % 100}"
    if style == 3:
        return f"{d.day:02d}.{d.month:02d}.{d.year}"
    return d  # real excel date


