def crm():
    """Old CRM export: some phones differ (older/newer), some expiries older (last year)."""
    rows = []
    pick = [0, 1, 2, 3, 5, 6, 8, 10, 11, 12, 13, 15, 17, 18, 20, 22, 23, 24, 27, 29]
    for k, i in enumerate(pick):
        n, pl, ph, prog, exp, last, cons, note, m, debt = CARS[i]
        sur, first = n.split(" ", 1)[0], n.split(" ", 1)[1] if " " in n else ""
        phone = "".join(ch for ch in ph.split("(")[0] if ch.isdigit())
        if k % 4 == 1:
            phone = phone[:-1] + str((int(phone[-1]) + 3) % 10)   # older phone, conflicts with xlsx
        e = d_in(exp)
        if k % 3 == 0:
            e = date(e.year - 1, e.month, e.day)                  # old expiry, conflicts with xlsx
        status = ["Ενεργό", "ΕΝΕΡΓΟ", "Ληγμένο", "ενεργο"][k % 4]
        rows.append([sur.replace("ü", "ue").upper(), first, phone, pl.replace("-", ""), e.strftime("%d/%m/%Y"), status, "παλιά εγγραφή" if k % 5 == 0 else ""])
    rows.append(["ΜΑΡΙΝΟΠΟΥΛΟΣ", "Ιάκωβος", "6900000160", "ΝΑΒ 4410", "03/03/2026", "Ληγμένο", "έφυγε σε άλλο γραφείο"])
