def sheet_title(ws, title, groups, ncols):
    ws["A1"] = title
    ws["A1"].font = Font(bold=True, size=14)
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncols)
    for (a, b, text) in groups:
        ws.cell(row=2, column=a, value=text)
        ws.merge_cells(start_row=2, start_column=a, end_row=2, end_column=b)
        ws.cell(row=2, column=a).alignment = Alignment(horizontal="center")
        ws.cell(row=2, column=a).fill = PatternFill("solid", fgColor="DDDDDD")


